from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from datetime import UTC
from pathlib import Path

GENESIS_HASH = "0" * 64


def canonical_json(obj: dict) -> str:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), default=str)


def compute_hash(prev_hash: str, record: dict) -> str:
    payload = canonical_json({**record, "prev_hash": prev_hash})
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def hashable_fields(forecast_row) -> dict:
    """The exact fields covered by the chain, excluding the chain fields
    themselves and the unpublished rationale."""
    return {
        "question_id": forecast_row.question_id,
        "created_at": forecast_row.created_at.isoformat(),
        "model": forecast_row.model,
        "prompt_version": forecast_row.prompt_version,
        "prompt_sha256": forecast_row.prompt_sha256,
        "raw_prob": forecast_row.raw_prob,
        "calibrated_prob": forecast_row.calibrated_prob,
        "calibrator_version": forecast_row.calibrator_version,
    }


@dataclass
class ChainBreak:
    index: int
    expected: str
    found: str


def verify_chain(forecasts: list) -> ChainBreak | None:
    """`forecasts` must be ordered by creation time (ascending). Returns None
    if the chain verifies end to end, else the first break found."""
    prev_hash = GENESIS_HASH
    for i, row in enumerate(forecasts):
        expected = compute_hash(prev_hash, hashable_fields(row))
        if expected != row.hash:
            return ChainBreak(index=i, expected=expected, found=row.hash)
        if row.prev_hash != prev_hash:
            return ChainBreak(index=i, expected=prev_hash, found=row.prev_hash)
        prev_hash = row.hash
    return None


def next_chain_link(prev_hash: str, forecast_fields: dict) -> tuple[str, str]:
    """Returns (prev_hash, hash) to store on a new forecast row."""
    return prev_hash, compute_hash(prev_hash, forecast_fields)


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def build_site(output_dir: str, questions: list, forecasts_by_question: dict[str, list]) -> None:
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    track_record = []
    for q in questions:
        q_forecasts = forecasts_by_question.get(q.id, [])
        if not q_forecasts:
            continue
        latest = q_forecasts[-1]
        track_record.append(
            {
                "id": q.id,
                "title": q.title,
                "url": q.url,
                "status": q.status,
                "resolution": q.resolution,
                "latest_prob": latest.calibrated_prob
                if latest.calibrated_prob is not None
                else latest.raw_prob,
                "forecast_count": len(q_forecasts),
            }
        )

    (out / "track-record.json").write_text(json.dumps(track_record, indent=2, default=str))
    (out / "index.html").write_text(_render_html(track_record))

    manifest = {
        "generated_at": _now_iso(),
        "question_count": len(track_record),
        "files": {name: sha256_file(out / name) for name in ("index.html", "track-record.json")},
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2))


def _now_iso() -> str:
    from datetime import datetime

    return datetime.now(UTC).isoformat()


def _render_html(track_record: list[dict]) -> str:
    rows = "\n".join(
        f'<tr><td><a href="{r["url"]}">{r["title"]}</a></td>'
        f"<td>{r['status']}</td><td>{r['latest_prob']:.2f}</td>"
        f"<td>{r['resolution'] if r['resolution'] is not None else '—'}</td></tr>"
        for r in track_record
    )
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>LLM Forecast Pipeline — Track Record</title>
</head>
<body>
<h1>LLM Forecast Pipeline — Public Track Record</h1>
<p>Not investment advice. Probabilities are generated by a language model and
have not been independently verified. See the repository README for
methodology, scoring, and the hash chain that makes this history
tamper-evident.</p>
<table border="1" cellpadding="6">
<thead>
<tr><th>Question</th><th>Status</th><th>Latest probability</th><th>Resolution</th></tr>
</thead>
<tbody>
{rows}
</tbody>
</table>
</body>
</html>
"""
